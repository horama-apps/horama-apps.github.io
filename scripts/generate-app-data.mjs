import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { parse } from "yaml";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const sourcePath = join(root, "data", "apps.yaml");
const translationPath = join(root, "data", "en.yaml");
const outputPath = join(root, "data", "apps.generated.ts");
const source = await readFile(sourcePath, "utf8");
const translationSource = await readFile(translationPath, "utf8");
const data = parse(source);
const translations = parse(translationSource);

const output = `// Generated from data/apps.yaml and data/en.yaml. Do not edit this file directly.\nexport const siteData = ${JSON.stringify(data, null, 2)} as const;\nexport const siteTranslations = ${JSON.stringify(translations, null, 2)} as const;\n`;

await writeFile(outputPath, output, "utf8");
console.log("Generated data/apps.generated.ts from data/apps.yaml");
